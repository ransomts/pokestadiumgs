#!/home/tsranso/Code/pokestadiumgs/.venv/bin/python3
"""Adopt a candidate as the real C: splice it over the pragma, drop the splice markers,
and run the full make. Keeps the change only if the ROM prints `build/pokestadiumgs-us.z64: OK`
(otherwise the file is restored). On success also deletes the now-unreferenced .s under
asm/us/nonmatchings/ (that tree is regenerated by extract, so one stale file is safe to remove).

usage: .venv/bin/python3 matching_notes/adopt_candidate.py src/path/file.c func_XXXXXXXX path/to/source.c

GS port notes vs the Stadium 1 tool: there is no NON_MATCHING draft wrapper to strip --
the S1 wrapper-removal step (#if 1/#else/#endif around the pragma) is replaced by dropping
mkdraft's splice markers; the full-make gate is the literal line
`build/pokestadiumgs-us.z64: OK` (md5sum -c of the built ROM; S1 grepped for
`build/pokestadium-us.z64: OK`). Never run `make extract`; the .s removal only touches
the single file the adopted function's pragma referenced.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PY = os.path.join(REPO, ".venv", "bin", "python3")
ROM_OK = "build/pokestadiumgs-us.z64: OK"
sys.path.insert(0, HERE)
import mkdraft

if len(sys.argv) != 4:
    sys.exit(__doc__)
src, func, cand = sys.argv[1:4]
path = os.path.join(REPO, src)
with open(path) as f:
    orig = f.read()

# the .s the pragma referenced (for post-adoption cleanup); may live in orig or in .pre
asm = None
pm = mkdraft.pragma_re(func).search(orig)
if pm:
    asm = pm.group(1)
else:
    pre = os.path.join(mkdraft.DRAFTS, func + ".pre")
    if os.path.exists(pre):
        with open(pre) as f:
            pp = mkdraft.pragma_re(func).search(f.read())
        asm = pp.group(1) if pp else None

# 1. splice + score the candidate (kept in place, mkdraft markers around it)
r = subprocess.run([PY, os.path.join(HERE, "try_candidate.py"), src, func, cand, "--keep"])
if r.returncode != 0:
    mkdraft.write_and_touch(path, orig)
    sys.exit("adopt_candidate: try_candidate failed; file restored")

# 2. drop the splice markers: the candidate is now plain C where the pragma was
with open(path) as f:
    t = f.read()
u = mkdraft.unwrap(t, func)
if u is None:
    mkdraft.write_and_touch(path, orig)
    sys.exit("adopt_candidate: mkdraft markers not found after splice; file restored")
mkdraft.write_and_touch(path, u)

# 3. full make; the gate is the literal OK line (never `make extract`, never partial)
env = dict(os.environ, PATH="%s:%s:%s" % (os.path.join(REPO, ".venv", "bin"),
                                           os.path.join(os.path.expanduser("~"), "local", "bin"),
                                           os.environ.get("PATH", "")))
r = subprocess.run(["make", "-j32", "PYTHON=%s" % PY], cwd=REPO, env=env,
                   capture_output=True, text=True)
lines = [l for l in r.stdout.splitlines() if l.strip()]
last = lines[-1] if lines else ""
print(last)
if last.strip() != ROM_OK:
    mkdraft.write_and_touch(path, orig)
    print("adopt_candidate: not OK (rc=%d); file restored" % r.returncode)
    sys.exit(1)

# 4. success: the pragma is gone, so its .s under asm/us/nonmatchings is stale
if asm and asm.startswith("asm/us/nonmatchings/") and os.path.isfile(os.path.join(REPO, asm)):
    os.remove(os.path.join(REPO, asm))
    print("adopt_candidate: removed stale %s" % asm)
# splice state is stale now (there is no marker block to restore any more)
for suffix in (".pre", ".src"):
    p = os.path.join(mkdraft.DRAFTS, func + suffix)
    if os.path.exists(p):
        os.remove(p)
print("adopt_candidate: %s adopted in %s" % (func, src))
